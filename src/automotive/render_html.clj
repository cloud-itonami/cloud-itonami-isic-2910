(ns automotive.render-html
  "Build-time HTML renderer for `docs/samples/operator-console.html`.

  Closes flagship checklist item 2 (ADR-2607189300 at
  `com-junkawasaki/root`, ledger seq 3 diagnosis / seq 4 fix): this page
  was previously a ONE-TIME hand-pasted transcript of a
  `clojure -M:dev:run` console session -- despite its own caption
  claiming 'Demo snapshot -- live data from `automotive.store` /
  `clojure -M:dev:run`', the file was never actually regenerated by
  running that command again (git history: exactly one commit ever
  touched it, alongside the whole `docs/` tree, no companion script).

  This namespace makes that caption true: it runs the SAME
  motor-vehicle demo scenario `automotive.sim`/`automotive.export-run`
  already exercise, through the REAL actor stack
  (`automotive.operation` -> `automotive.governor` ->
  `automotive.store`), and renders the result deterministically.
  No invented numbers, no timestamps in the page content -- reruns
  against the same fresh seed produce byte-identical output (verified
  by diffing two consecutive runs), so nightly regeneration only ever
  commits when the actor's real behavior actually changes, the same
  'commit-only-on-change' discipline `cloud-itonami-isic-6399`'s
  `web/generate.cljs` + `regenerate.yml` established for this fleet.

  Usage: `clojure -M:dev:render-html [out-file]`
  (default `docs/samples/operator-console.html`)."
  (:require [clojure.string :as str]
            [automotive.store :as store]
            [automotive.export :as export]
            [automotive.operation :as op]
            [langgraph.graph :as g]))

(def ^:private operator
  {:actor-id "op-1" :actor-role :homologation-engineer :phase 3})

(defn- exec! [actor tid request]
  (g/run* actor {:request request :context operator} {:thread-id tid}))

(defn- approve! [actor tid]
  (g/run* actor {:approval {:status :approved :by "op-1"}}
          {:thread-id tid :resume? true}))

(defn run-demo!
  "Runs a fresh seeded store through the same interesting-state
  scenario this page has always described: vehicle-1 clears the full
  lifecycle (intake -> type-approval verify -> end-of-line screen ->
  robotics/CAE assembly-line check -> vehicle-dispatch -> Certificate
  of Conformity, each human-gated step actually approved); vehicle-2
  HARD-holds on a missing type-approval spec basis (never reaches a
  human); vehicle-3 clears verification and its own robotics/CAE
  check but HARD-holds at dispatch on an out-of-range emissions
  deviation; vehicle-4 HARD-holds on an unresolved end-of-line defect
  (never reaches a human). Returns the resulting store -- every field
  read by `render` below is real governor/store output, not a
  hand-typed copy."
  []
  (let [db (store/seed-db)
        actor (op/build db)]
    (exec! actor "v1-intake" {:op :vehicle/intake :subject "vehicle-1"
                               :patch {:id "vehicle-1" :vehicle-name "Sakura Compact Sedan CS-04"}})
    (exec! actor "v1-verify" {:op :type-approval-rules/verify :subject "vehicle-1"})
    (approve! actor "v1-verify")
    (exec! actor "v1-eol" {:op :end-of-line-quality/screen :subject "vehicle-1"})
    (approve! actor "v1-eol")
    (exec! actor "v1-robotics" {:op :robotics/simulate-assembly-line :subject "vehicle-1"})
    (approve! actor "v1-robotics")
    (exec! actor "v1-dispatch" {:op :actuation/dispatch-vehicle :subject "vehicle-1"})
    (approve! actor "v1-dispatch")
    (exec! actor "v1-cert" {:op :actuation/issue-conformity-certificate :subject "vehicle-1"})
    (approve! actor "v1-cert")

    (exec! actor "v2-verify" {:op :type-approval-rules/verify :subject "vehicle-2" :no-spec? true})

    (exec! actor "v3-verify" {:op :type-approval-rules/verify :subject "vehicle-3"})
    (approve! actor "v3-verify")
    (exec! actor "v3-robotics" {:op :robotics/simulate-assembly-line :subject "vehicle-3"})
    (approve! actor "v3-robotics")
    (exec! actor "v3-dispatch" {:op :actuation/dispatch-vehicle :subject "vehicle-3"})

    (exec! actor "v4-eol" {:op :end-of-line-quality/screen :subject "vehicle-4"})
    db))

