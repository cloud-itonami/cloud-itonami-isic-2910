(defn- esc [v]
  (-> (str v)
      (str/replace "&" "&amp;")
      (str/replace "<" "&lt;")
      (str/replace ">" "&gt;")))

(defn- last-fact-for [ledger vehicle-id]
  (last (filter #(= (:subject %) vehicle-id) ledger)))

(defn- emissions-cell [{:keys [emissions-deviation-actual emissions-deviation-min emissions-deviation-max]}]
  (if (and (number? emissions-deviation-actual)
           (<= emissions-deviation-min emissions-deviation-actual emissions-deviation-max))
    (format "<span class=\"ok\">%.2f &isin; [%.2f,%.2f]</span>"
            (double emissions-deviation-actual) (double emissions-deviation-min) (double emissions-deviation-max))
    (format "<span class=\"err\">%.2f out of range</span>" (double emissions-deviation-actual))))

(defn- eol-cell [{:keys [eol-defect-unresolved?]}]
  (if eol-defect-unresolved?
    "<span class=\"err\">unresolved</span>"
    "<span class=\"ok\">resolved</span>"))

(defn- status-cell [ledger {:keys [id vehicle-dispatched? conformity-certified?]}]
  (let [last-fact (last-fact-for ledger id)]
    (cond
      (and vehicle-dispatched? conformity-certified?)
      "<span class=\"ok\">ready</span>"

      (= :hold (:disposition last-fact))
      (let [rule (-> last-fact :violations first :rule)]
        (case rule
          :no-spec-basis "<span class=\"err\">no spec-basis</span>"
          :end-of-line-defect-unresolved "<span class=\"critical\">EOL hold</span>"
          :vehicle-emissions-out-of-range "<span class=\"warn\">HARD hold on dispatch</span>"
          (str "<span class=\"warn\">HARD hold: " (esc (name (or rule :unknown))) "</span>")))

      :else "<span class=\"muted\">in progress</span>")))

(defn- vehicle-row [ledger {:keys [id vehicle-name jurisdiction] :as vehicle}]
  (format "        <tr><td>%s</td><td>%s</td><td>%s</td><td>%s</td><td>%s</td><td>%s</td></tr>"
          (esc id) (esc vehicle-name) (esc jurisdiction)
          (emissions-cell vehicle) (eol-cell vehicle) (status-cell ledger vehicle)))

(defn- record-row [record kind note]
  (format "        <tr><td>%s</td><td>%s</td><td>%s</td></tr>"
          (esc (get record "record_id")) (esc kind) (esc note)))

(def ^:private action-gate-rows
  ;; Static description of this actor's own op contract (README `Ops`
  ;; table, `automotive.governor`/`automotive.phase`) -- documentation
  ;; of fixed behavior, not runtime telemetry, so it is legitimately
  ;; hand-described rather than derived from a live run.
  ["        <tr><td><code>:vehicle/intake</code></td><td>none</td><td><span class=\"ok\">phase-3 auto when clean</span></td></tr>"
   "        <tr><td><code>:type-approval-rules/verify</code></td><td>none</td><td><span class=\"warn\">human approval &middot; no fabricated type-approval rules</span></td></tr>"
   "        <tr><td><code>:end-of-line-quality/screen</code></td><td>none</td><td><span class=\"critical\">HARD hold if unresolved defect</span></td></tr>"
   "        <tr><td><code>:robotics/simulate-assembly-line</code></td><td>none</td><td><span class=\"warn\">human approval &middot; real physics-2d CAE check</span></td></tr>"
   "        <tr><td><code>:actuation/dispatch-vehicle</code></td><td class=\"critical\">safety-critical</td><td><span class=\"warn\">always human &middot; emissions + robotics-sim checks</span></td></tr>"
   "        <tr><td><code>:actuation/issue-conformity-certificate</code></td><td class=\"critical\">safety-critical</td><td><span class=\"warn\">always human &middot; EOL + double-issue guard</span></td></tr>"])

(defn render
  "Renders the full operator-console.html document from a store `db`
  that has already run `run-demo!` (or any other real scenario)."
  [db]
  (let [ledger (vec (store/ledger db))
        vehicles (->> (export/vehicles-snapshot db)
                      (filter #(#{"vehicle-1" "vehicle-2" "vehicle-3" "vehicle-4"} (:id %)))
                      (sort-by :id))
        dispatches (store/dispatch-history db)
        certs (store/evidence-history db)
        vehicle-rows (str/join "\n" (map (partial vehicle-row ledger) vehicles))
        dispatch-rows (str/join "\n" (map #(record-row % "vehicle-dispatch-draft" "unsigned · plant signs offline") dispatches))
        cert-rows (str/join "\n" (map #(record-row % "conformity-certificate-draft" "unsigned · type-approval authority submission is plant act") certs))
        handoff-rows (str/join "\n" (remove str/blank? [dispatch-rows cert-rows]))]
    (str
     "<html><head><meta charset=\"utf-8\"><title>cloud-itonami-isic-2910 · motor-vehicle plant</title><style>\n"
     "table { width: 100%; border-collapse: collapse; font-size: 14px; }\n"
     ".ok { color: #137a3f; }\n"
     "body { font-family: system-ui,-apple-system,sans-serif; margin: 0; color: #1a1a1a; background: #fafafa; }\n"
     "header.bar { display: flex; align-items: center; gap: 12px; padding: 12px 20px; background: #fff; border-bottom: 1px solid #e5e5e5; }\n"
     "th, td { text-align: left; padding: 8px 10px; border-bottom: 1px solid #f0f0f0; }\n"
     "h2 { margin-top: 0; font-size: 15px; }\n"
     ".warn { color: #b25c00; background: #fff8e1; padding: 2px 6px; border-radius: 4px; }\n"
     "main { max-width: 980px; margin: 24px auto; padding: 0 20px; }\n"
     "header.bar h1 { font-size: 18px; margin: 0; font-weight: 600; }\n"
     ".muted { color: #888; font-size: 13px; }\n"
     ".critical { color: #fff; background: #b3261e; padding: 2px 6px; border-radius: 4px; font-weight: 600; }\n"
     ".card { background: #fff; border: 1px solid #e5e5e5; border-radius: 8px; padding: 16px; margin-bottom: 16px; }\n"
     ".err { color: #b3261e; background: #fbe9e7; padding: 2px 6px; border-radius: 4px; }\n"
     "th { font-weight: 600; color: #555; font-size: 12px; text-transform: uppercase; letter-spacing: 0.04em; }\n"
     "header.bar .badge { margin-left: auto; font-size: 12px; color: #666; }\n"
     "code { font-size: 12px; background: #f4f4f4; padding: 1px 4px; border-radius: 3px; }\n"
     "</style></head><body>\n"
     "<header class=\"bar\">\n"
     "  <h1>Motor-vehicle plant (ISIC 2910) — Operator Console</h1>\n"
     "  <span class=\"badge\">read-only sample · governor-gated · never dispatches hardware</span>\n"
     "</header>\n"
     "<main>\n"
     "  <section class=\"card\">\n"
     "    <h2>Vehicles</h2>\n"
     "    <p class=\"muted\">Demo snapshot — build-time-generated from <code>automotive.store</code> via <code>automotive.render-html</code> (<code>clojure -M:dev:render-html</code>), regenerated nightly.</p>\n"
     "    <table>\n"
     "      <thead><tr><th>Vehicle</th><th>Name</th><th>Jurisdiction</th><th>Emissions</th><th>EOL</th><th>Status</th></tr></thead>\n"
     "      <tbody>\n"
     vehicle-rows "\n"
     "      </tbody>\n"
     "    </table>\n"
     "  </section>\n"
     "  <section class=\"card\">\n"
     "    <h2>Action gate (Automotive Governor)</h2>\n"
     "    <p class=\"muted\">HARD holds cannot be overridden. Actuation always escalates to a human homologation engineer.</p>\n"
     "    <table>\n"
     "      <thead><tr><th>Op</th><th>Stake</th><th>Gate</th></tr></thead>\n"
     "      <tbody>\n"
     (str/join "\n" action-gate-rows) "\n"
     "      </tbody>\n"
     "    </table>\n"
     "  </section>\n"
     "  <section class=\"card\">\n"
     "    <h2>Social hand-off</h2>\n"
     "    <p class=\"muted\">Audit package for type-approval inspectors / market-regulator inspectors — <code>automotive.export/audit-package</code> and <code>package-&gt;csv-bundle</code> (vehicles / ledger / dispatches / conformity-certificates CSV).</p>\n"
     "    <table>\n"
     "      <thead><tr><th>Artifact</th><th>Kind</th><th>Note</th></tr></thead>\n"
     "      <tbody>\n"
     handoff-rows "\n"
     "      </tbody>\n"
     "    </table>\n"
     "  </section>\n"
     "</main>\n"
     "</body></html>\n")))

(defn -main [& args]
  (let [out (or (first args) "docs/samples/operator-console.html")
        db (run-demo!)
        html (render db)]
    (spit out html)
    (println "wrote" out "(" (count (store/ledger db)) "ledger facts,"
             (count (store/dispatch-history db)) "dispatches,"
             (count (store/evidence-history db)) "conformity certificates )")))
